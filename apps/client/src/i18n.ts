const DICTS: Record<Lang, Dict> = { en, el };

/** Translate a key, replacing {placeholders}. Unknown key → visible fallback. */
export function tr(lang: Lang, key: StringKey, vars?: Record<string, string | number>): string {
  let text: string = DICTS[lang][key] ?? DICTS.en[key] ?? String(key);
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

/** The t() every screen uses — always in the user's chosen language. */
export function useT() {
  const lang = useStore((s) => s.language);
  return useMemo(
    () => (key: StringKey, vars?: Record<string, string | number>) => tr(lang, key, vars),
    [lang],
  );
}

